"""Build the static English page and sitemap from the Spanish page and shared copy."""
import argparse
import json
from pathlib import Path
import subprocess

from bs4 import BeautifulSoup, Comment

SITE = Path(__file__).resolve().parent
BASE = "https://bultodepapas.github.io/OpenRCsimulator/"


def load_copy():
    # Evaluate only the repository-owned data file, with no browser or Node globals.
    program = """
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(process.argv[1], 'utf8');
const data = vm.runInNewContext(source + '\\nJSON.stringify({translations, aircraft, labels, alts, englishMetadata, englishAttributes})', {}, {timeout: 1000});
process.stdout.write(data);
"""
    return json.loads(subprocess.check_output(
        ["node", "-e", program, str(SITE / "content.js")], text=True
    ))


def replace_html(element, markup):
    fragment = BeautifulSoup("<div>" + markup + "</div>", "html.parser").div
    element.clear()
    for child in list(fragment.contents):
        element.append(child)


def build():
    data = load_copy()
    soup = BeautifulSoup((SITE / "index.html").read_text(encoding="utf-8"), "html.parser")
    if soup.html["lang"] != "es":
        raise ValueError("index.html must remain the Spanish source page")
    expected_alternates = {"es": BASE, "en": BASE + "en.html", "x-default": BASE}
    actual_alternates = {tag["hreflang"]: tag["href"] for tag in soup.select('link[rel="alternate"][hreflang]')}
    if actual_alternates != expected_alternates:
        raise ValueError("Spanish page must declare both locales and the default")
    if soup.select_one('link[rel="canonical"]')["href"] != BASE:
        raise ValueError("Spanish canonical must be the project root")
    soup.html["lang"] = "en"
    soup.insert(1, Comment(" Generated by build_locales.py; edit index.html and content.js. "))
    for element in soup.select('[data-i18n]'):
        key = element["data-i18n"]
        copy = data["translations"][key]  # Missing translations must block publication.
        if not copy.strip():
            raise ValueError(f"Empty English translation: {key}")
        replace_html(element, copy)
    for attribute, dictionary, target in [("data-label", "labels", "aria-label"), ("data-alt", "alts", "alt")]:
        for element in soup.select(f'[{attribute}]'):
            element[target] = data[dictionary][element[attribute]][1]
    for element in soup.select('[aria-label], [alt]'):
        for attribute in ("aria-label", "alt"):
            value = element.get(attribute)
            if value in data["englishAttributes"]:
                element[attribute] = data["englishAttributes"][value]

    language = soup.select_one('.language')
    language["href"] = "./"
    language["lang"] = language["hreflang"] = "es"
    language["aria-label"] = "Cambiar a español"
    language.string = "ES"
    jet = data["aircraft"]["jet"]
    for selector, value in {
        "#aircraft-category": jet["category"][1],
        "#aircraft-description": jet["description"][1],
        "#aircraft-gear": jet["gear"][1],
    }.items():
        soup.select_one(selector).string = value

    title = data["englishMetadata"]["title"]
    description = data["englishMetadata"]["description"]
    soup.title.string = title
    for selector in ['meta[property="og:title"]', 'meta[name="twitter:title"]']:
        soup.select_one(selector)["content"] = title
    for selector in ['meta[name="description"]', 'meta[property="og:description"]', 'meta[name="twitter:description"]']:
        soup.select_one(selector)["content"] = description
    url = BASE + "en.html"
    soup.select_one('link[rel="canonical"]')["href"] = url
    soup.select_one('meta[property="og:url"]')["content"] = url
    schema_element = soup.select_one('#software-schema')
    schema = json.loads(schema_element.string)
    schema.update(description=description, url=url, downloadUrl=url + "#download")
    schema["offers"]["url"] = url + "#download"
    schema_element.string = "\n" + json.dumps(schema, ensure_ascii=False, indent=2) + "\n"

    sitemap = '\n'.join([
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        f'  <url><loc>{BASE}</loc></url>',
        f'  <url><loc>{url}</loc></url>',
        '</urlset>', '',
    ])
    return {"en.html": str(soup) + "\n", "sitemap.xml": sitemap}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale; do not write.")
    args = parser.parse_args()
    outputs = build()
    if args.check:
        stale = [name for name, content in outputs.items()
                 if not (SITE / name).exists() or (SITE / name).read_text(encoding="utf-8") != content]
        if stale:
            raise SystemExit("Stale generated files: " + ", ".join(stale) + ". Run python3 site/build_locales.py")
        print("Static English page and sitemap match their sources.")
    else:
        for name, content in outputs.items():
            (SITE / name).write_text(content, encoding="utf-8")
        print("Generated " + ", ".join(outputs))


if __name__ == "__main__":
    main()
