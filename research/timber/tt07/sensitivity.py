#!/usr/bin/env python3
"""TT-07: bound every declared estimate while preserving manual mass and CG."""
import argparse
import copy
import json
from derive_physics import derive, HERE


def summary(inputs):
    model, result = derive(inputs)
    p=model['propulsion'];kv=p['motor']['kv_rpm_per_volt']['value']
    resistance=p['motor']['resistance_ohm']['value'];i0=p['motor']['no_load_current_a']['value']
    voltage=p['battery']['voltage_v']['value'];diameter=p['propeller']['diameter']['value']
    cp=p['propeller']['cp_table']['value'][0][1];ct=p['propeller']['ct_table']['value'][0][1]
    kt=60/(2*3.141592653589793*kv)
    lo,hi=0.,voltage*kv
    for _ in range(80):
        rpm=(lo+hi)/2;n=rpm/60
        current=max(0,(voltage-rpm/kv)/resistance)
        torque=kt*(current-i0)
        load=cp*1.225*n*n*diameter**5/(2*3.141592653589793)
        if torque>load:lo=rpm
        else:hi=rpm
    rpm=(lo+hi)/2
    result.update(static_rpm=rpm,static_current=(voltage-rpm/kv)/resistance,
                  static_thrust=ct*1.225*(rpm/60)**2*diameter**4,
                  aileron_deg=model['controls']['max_throw']['aileron']['value'],
                  Cma=model['aero']['coefficients']['Cma']['value'],
                  Clb=model['aero']['coefficients']['Clb']['value'],
                  Clda=model['aero']['coefficients']['Clda_right']['value'],
                  tail_effectiveness=model['aero']['surfaces']['horizontal']['control_effectiveness']['value'],
                  gear_stiffness=sum(c['stiffness']['value'] for c in model['landing_gear']['contacts']))
    return result


def report():
    inputs=json.loads((HERE/'inputs.json').read_text(encoding='utf-8'))
    base=summary(inputs)
    lines=['# TT-07 estimate sensitivity', '', 'Generated by `sensitivity.py`; endpoints are assumptions, not confidence bounds. Each row varies one estimate; manual total mass and longitudinal CG remain fixed by the declared virtual balance. Context-only quantities may have no effect. This is an offline model study, not physical validation.', '',
           '| Estimate | Range | Result at low / high |', '| --- | --- | --- |']
    for name,spec in inputs['estimates'].items():
        endpoints=[]
        for endpoint in spec['range']:
            variant=copy.deepcopy(inputs);variant['estimates'][name]['value']=endpoint
            try:
                current=summary(variant)
                delta={k:v for k,v in current.items() if v!=base[k]}
                # Scalar outputs plus all inertia entries; keep the table readable.
                entries=[]
                for k,v in delta.items():
                    if k=='cg':continue
                    if isinstance(v,list):entries.append(k+'=['+', '.join(f'{n:.5g}' for n in v)+']')
                    else:entries.append(f'{k}={v:.5g}')
                endpoints.append('; '.join(entries) or 'no change in reported observables (context/domain input)')
            except ValueError as error:endpoints.append('REFUSED: '+str(error))
        lines.append(f"| `{name}` | {spec['range']} | {' / '.join(endpoints)} |")
    lines += ['', 'The +/-76.6 mm nose row moves motor, ESC and propeller stations, then rebalances at the same CG. The two-blade Ct/Cp rows vary independently. Neither bounds a matched three-blade map. Negative or out-of-body residual balancing stations are refused. Per-component uncertainties are not identified; the common component-mass row and nose row do not claim to bound them.', '']
    return '\n'.join(lines)


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=HERE/'sensitivity.md';text=report()
    if args.check:
        if not path.exists() or path.read_bytes()!=text.encode('utf-8'):raise SystemExit('TT-07 sensitivity stale')
        print('TT-07 estimate sensitivity current')
    else:path.write_bytes(text.encode('utf-8'));print('TT-07 estimate sensitivity written')
