"""Generate MoonRunner presentation geometry from the frozen r4 geometry and verified derivative GLB."""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ORIGINAL = "3e14a512fac3048e45cdeb46cbad7cc16f20fe41e5b6957b7df516c80a9b17ac"
DERIVATIVE = "54d67d9bbfe4ce4abdc4bafa523c3bf812422d6336ba1d0f151a2970e087b0f0"
BOLIDO = "9ecaf7b49aec555bbea178b3b582378bb362bec3f816448932438db2c8da8f93"
ORIGINAL_SOURCE = "0fbf3d27b932ec0b477355deabcad724b306e3a5d482d594665b24eb214e6df6"
OLD_GLB = "app/assets/aircraft/skywalker-x8/skywalker_x8.glb"
NEW_GLB = "app/assets/aircraft/moonrunner-x99/moonrunner_x99.glb"
BOLIDO_GLB = "app/assets/aircraft/moonrunner-x99/moonrunner_x99_bolido.glb"
SOURCE = "assets/aircraft/skywalker-x8/model-geometry.json"
OUT_JSON = "assets/aircraft/moonrunner-x99-overlay/model-geometry.json"
OUT_GD = "app/aircraft/moonrunner_x99_geometry.gd"
SCRIPT = "research/aircraft-standardization/build_moonrunner_geometry.py"


def glb(path: Path, expected: str):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != expected:
        raise ValueError(f"unexpected GLB identity: {path}")
    if len(raw) < 28:
        raise ValueError("incomplete GLB")
    magic, version, total = struct.unpack_from("<4sII", raw)
    if (magic, version, total) != (b"glTF", 2, len(raw)):
        raise ValueError("invalid GLB header")
    length, kind = struct.unpack_from("<II", raw, 12)
    if kind != 0x4E4F534A or 20 + length + 8 > len(raw):
        raise ValueError("invalid GLB JSON chunk")
    document = json.loads(raw[20:20 + length])
    offset = 20 + length
    size, kind = struct.unpack_from("<II", raw, offset)
    if kind != 0x004E4942 or offset + 8 + size != len(raw):
        raise ValueError("invalid GLB binary chunk")
    return document, raw[offset + 8:]


def verify_equivalence(old, old_bin, new, new_bin):
    for key in ("scene", "scenes", "nodes", "meshes", "accessors", "materials", "textures", "samplers", "animations", "skins"):
        if old.get(key) != new.get(key):
            raise ValueError(f"GLB {key} differs")
    for index, (left, right) in enumerate(zip(old["accessors"], new["accessors"])):
        if "bufferView" not in left:
            raise ValueError("sparse or missing accessor views are unsupported")
        a = old["bufferViews"][left["bufferView"]]
        b = new["bufferViews"][right["bufferView"]]
        if any(a.get(k) != b.get(k) for k in ("buffer", "byteLength", "byteStride", "target")):
            raise ValueError(f"accessor {index} buffer view metadata differs")
        aa = old_bin[a.get("byteOffset", 0):a.get("byteOffset", 0) + a["byteLength"]]
        bb = new_bin[b.get("byteOffset", 0):b.get("byteOffset", 0) + b["byteLength"]]
        if len(aa) != a["byteLength"] or len(bb) != b["byteLength"] or aa != bb:
            raise ValueError(f"accessor {index} data differs")


def generate(root: Path, check: bool):
    source_bytes = (root / SOURCE).read_bytes().replace(b"\r\n", b"\n")
    if hashlib.sha256(source_bytes).hexdigest() != ORIGINAL_SOURCE:
        raise ValueError("historical geometry source identity changed")
    old, old_bin = glb(root / OLD_GLB, ORIGINAL)
    new, new_bin = glb(root / NEW_GLB, DERIVATIVE)
    verify_equivalence(old, old_bin, new, new_bin)
    if hashlib.sha256((root / BOLIDO_GLB).read_bytes()).hexdigest() != BOLIDO:
        raise ValueError("BOLIDO copy identity changed")
    data = json.loads(source_bytes)
    if data["inputs"]["glb_sha256"] != ORIGINAL or data["liveries"][0]["glb_sha256"] != ORIGINAL:
        raise ValueError("historical geometry input does not match original GLB")
    data["catalog_id"] = "moonrunner-x99"
    data["revision"] = "moonrunner-x99-54d67d9bbfe4"
    data["source_alias"] = "MoonRunner X99 visual derivative of Skywalker X8 r4 delivery"
    data["status"] = "Paint derivative with the frozen r4 geometry, pivots and alternate livery."
    data["generator"] = SCRIPT
    data["inputs"]["glb_sha256"] = DERIVATIVE
    data["liveries"][0]["path"] = "res://" + NEW_GLB.removeprefix("app/")
    data["liveries"][0]["glb_sha256"] = DERIVATIVE
    if data["liveries"][1]["glb_sha256"] != BOLIDO:
        raise ValueError("historical BOLIDO identity changed")
    data["liveries"][1]["path"] = "res://" + BOLIDO_GLB.removeprefix("app/")
    outputs = {
        OUT_JSON: json.dumps(data, indent=1, ensure_ascii=False, allow_nan=False) + "\n",
        OUT_GD: (f"# Generated by {SCRIPT}; do not edit.\n"
                 "# Presentation measurements only; physical validation is separate.\nextends RefCounted\n\nconst DATA := "
                 + json.dumps(data, indent="\t", ensure_ascii=False, allow_nan=False) + "\n"),
    }
    for relative, value in outputs.items():
        path = root / relative
        payload = value.encode("utf-8")
        if check:
            if not path.is_file() or path.read_bytes() != payload:
                raise ValueError(f"stale generated geometry: {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.is_file() or path.read_bytes() != payload:
                path.write_bytes(payload)
    print("MoonRunner geometry " + ("is current" if check else "generated") + "; GLB geometry and UV accessors match")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args()
    try:
        generate(args.root.resolve(), args.check)
    except (ValueError, KeyError, OSError, struct.error) as exc:
        parser.exit(1, f"MoonRunner geometry failed: {exc}\n")


if __name__ == "__main__":
    main()
