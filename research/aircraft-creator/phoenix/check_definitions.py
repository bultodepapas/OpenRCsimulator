def model(body):
    return b'modelTypes.OwnedFixture = {' + body + b'}'


def run_synthetic():
    if not __debug__:
        raise ValueError('verification requires assertions; optimized Python is unsupported')
    checks = []

    def passed(name):
        checks.append({'name': name, 'result': 'passed'})

    def rejected(name, source, code=None):
        try:
            definition.inspect(source)
        except definition.DefinitionError as exc:
            assert code is None or exc.code == code, (name, exc.code, code)
            assert 0 <= exc.offset <= len(source) and exc.line >= 1 and exc.column >= 1
            checks.append({'name': name, 'result': 'rejected', 'code': exc.code})
        else:
            raise AssertionError('accepted out-of-profile definition: ' + name)

    source = b'-- owned fixture\r\nmodelTypes.OwnedFixture={name="x--y",values={-0.0,1.25,2,},physics=physics.airplane,}'
    parsed = definition.parse(source)
    fields = definition.fields(parsed.root)
    assert parsed.target == 'OwnedFixture'
    assert fields['name'].value == b'x--y'
    values = fields['values'].value
    assert [entry.value.value for entry in values] == [b'-0.0', b'1.25', b'2']
    for entry in values:
        assert source[entry.value.start:entry.value.end] == entry.value.value
    assert fields['physics'].value == b'physics.airplane'
    passed('CRLF, absent final newline, literal comment marker, exact numeric lexemes and source spans')
    helicopter = definition.inspect(model(b'physics=physics.helicopter'))
    assert helicopter['headers']['physics']['value']['display'] == 'physics.helicopter'
    passed('helicopter symbol retained as data')
    symbolic_lexeme = b'physics . -- source comment\n airplane'
    report = definition.inspect(model(b'physics=' + symbolic_lexeme))
    header = report['headers']['physics']
    assert header['value']['display'] == 'physics.airplane'
    assert header['value_representation'] == 'canonical symbolic name'
    assert bytes.fromhex(header['source_lexeme_raw_hex']) == symbolic_lexeme
    passed('canonical symbolic value is separate from its exact source lexeme')

    source = model(b'names={"\xc3\xa9","\xe9"}')
    nodes = definition.fields(definition.parse(source).root)['names'].value
    identities = [definition.string_identity(entry.value.value) for entry in nodes]
    assert identities[0]['display'] == identities[1]['display'] == 'é'
    assert identities[0]['raw_hex'] != identities[1]['raw_hex']
    assert [identity['display_decoding'] for identity in identities] == ['utf-8', 'latin-1']
    passed('equal displayed strings retain distinct bytes and display decoding')
    report = definition.inspect(model(b'a={Root_chord=1},b={Root_Chord=2}'))
    assert not report['diagnostics']
    parsed = definition.parse(model(b'Root_chord=1,Root_Chord=2'))
    assert list(definition.fields(parsed.root)) == ['Root_chord', 'Root_Chord']
    assert definition.summarize(parsed)['diagnostics'][0]['code'] == 'CASE_VARIANT_KEYS'
    passed('key case retained; same-table case variants diagnosed without overwriting')
    source = model(b'gear={{name="RUDDER",sides={{geometry={}}}},{name="RUDDER",sides={{geometry={}}}}}')
    report = definition.inspect(source)
    occurrences = [item for item in report['diagnostics'] if item['code'] == 'REPEATED_NAME']
    assert len(occurrences) == 2 and occurrences[0]['path'] != occurrences[1]['path']
    assert report['counts']['empty_geometry_lists'] == 2
    assert not any(item['severity'] == 'conversion_blocker' for item in report['diagnostics'])
    passed('repeated role names and empty geometry preserve separate structural identities')
    report = definition.inspect(model(b'body={geometry={"same"},collision={{node="same"}}}'))
    assert report['selected_reference_and_string_field_counts'] == {'node_string_field': 1, 'geometry_object': 1}
    assert not report['diagnostics']
    passed('one object may have separate geometry and collision roles')
    report = definition.inspect(model(b'a={Engine=100},b={Engine="source label"},c={Engine={Engine="nested"}}'))
    assert report['context_sensitive_field_kinds']['Engine'] == {'number': 1, 'string': 2, 'table': 1}
    passed('Engine field kind and context remain distinct')
    report = definition.inspect(model(b'body={geometry={"../../outside.geo","https://invalid.example/model"}}'))
    assert report['selected_reference_and_string_field_counts']['geometry_object'] == 2
    passed('reference strings remain data; parser has no dependency I/O')

    for name, source, code in [
        ('empty input', b'', 'UNSUPPORTED_SYNTAX'),
        ('opaque binary prefix', b'\x00\x01\xff', 'UNSUPPORTED_BYTE'),
        ('variant root is not an entire model', b'modelVariants.Fixture={}', 'UNSUPPORTED_SYNTAX'),
        ('second root assignment', model(b'') + b' modelTypes.Other={}', 'UNSUPPORTED_SYNTAX'),
        ('root scalar', b'modelTypes.OwnedFixture=1', 'ROOT_SHAPE'),
        ('root array', model(b'1'), 'ROOT_SHAPE'),
        ('duplicate exact key', model(b'name="first",name="second"'), 'DUPLICATE_KEY'),
        ('mixed table', model(b'list={x=1,2}'), 'MIXED_TABLE'),
        ('arbitrary function expression', model(b'x=call()'), 'UNSUPPORTED_BYTE'),
        ('arbitrary qualified symbol', model(b'x=unknown.member'), 'UNSUPPORTED_SYMBOL'),
        ('extra field after allowed symbol', model(b'x=physics.airplane.member'), 'UNSUPPORTED_SYNTAX'),
        ('identifier literal', model(b'x=true'), 'UNSUPPORTED_SYNTAX'),
        ('NaN identifier', model(b'x=NaN'), 'UNSUPPORTED_SYNTAX'),
        ('exponent number outside observed grammar', model(b'x=1e400'), 'UNSUPPORTED_SYNTAX'),
        ('hex number outside observed grammar', model(b'x=0x10'), 'UNSUPPORTED_SYNTAX'),
        ('number suffix', model(b'x=1.2abc'), 'UNSUPPORTED_SYNTAX'),
        ('partial decimal', model(b'x=1.'), 'UNSUPPORTED_SYNTAX'),
        ('string escape outside observed grammar', model(b'x="a\\b"'), 'UNSUPPORTED_ESCAPE'),
        ('control byte in string', model(b'x="a\x00b"'), 'STRING_CONTROL'),
        ('string newline', model(b'x="a\nb"'), 'STRING_CONTROL'),
        ('unterminated string', model(b'x="a'), 'UNTERMINATED_STRING'),
        ('block comment outside observed grammar', model(b'--[[ comment ]]\nx=1'), 'UNSUPPORTED_COMMENT'),
        ('bare CR cannot extend a line comment over unsupported syntax', b'-- note\runsupported()\n' + model(b''), 'UNSUPPORTED_LINE_ENDING'),
        ('bare CR locations need a separate profile', b'modelTypes.X={\rname="\xe9"}', 'UNSUPPORTED_LINE_ENDING'),
        ('non-ASCII identifier', model(b'\xe9=1'), 'UNSUPPORTED_BYTE'),
        ('missing comma', model(b'x=1 y=2'), 'UNSUPPORTED_SYNTAX'),
        ('truncated nested table', b'modelTypes.OwnedFixture={x={', 'UNSUPPORTED_VALUE'),
        ('unexpected punctuation', model(b'x=1;'), 'UNSUPPORTED_BYTE'),
    ]:
        rejected(name, source, code)

    for name, limit, value, source, code in [
        ('captured byte budget', 'MAX_INPUT', 4, model(b''), 'INPUT_LIMIT'),
        ('token budget', 'MAX_TOKENS', 5, model(b'x=1'), 'TOKEN_LIMIT'),
        ('node budget', 'MAX_NODES', 2, model(b'x={1}'), 'NODE_LIMIT'),
        ('table depth budget', 'MAX_DEPTH', 1, model(b'x={{1}}'), 'DEPTH_LIMIT'),
        ('string byte budget', 'MAX_STRING', 2, model(b'x="abc"'), 'STRING_LIMIT'),
        ('identifier byte budget', 'MAX_IDENTIFIER', 9, model(b'abcdefghij=1'), 'IDENTIFIER_LIMIT'),
        ('number byte budget', 'MAX_NUMBER', 3, model(b'x=1234'), 'NUMBER_LIMIT'),
        ('diagnostic budget', 'MAX_DIAGNOSTICS', 1, model(b'items={{name="x"},{name="x"}}'), 'DIAGNOSTIC_LIMIT'),
    ]:
        with patch.object(definition, limit, value):
            rejected(name, source, code)
    with patch.object(definition, 'MAX_REPORT_BYTES', 16):
        try:
            definition.inspect(model(b''))
        except ValueError as exc:
            assert 'report byte limit' in str(exc)
        else:
            raise AssertionError('report limit not enforced')
    passed('serialized report budget')
    with patch.object(definition, 'MAX_NUMBER', 512):
        rejected('finite float range after lexical budget', model(b'x=' + b'9' * 400), 'NUMBER_RANGE')
        rejected('nonzero decimal underflow', model(b'x=0.' + b'0' * 400 + b'1'), 'NUMBER_RANGE')

    def hinge(root, tip):
        return model(b'gear={{root_pivot={' + root + b'},tip_pivot={' + tip + b'}}}')

    def wheel(body):
        return model(b'gear={{wheels={{' + body + b'}}}}')

    origin = b'x=0,y=0,z=0'
    report = definition.inspect(hinge(origin, origin))
    assert report['diagnostics'][0]['code'] == 'COINCIDENT_PIVOTS'
    passed('exact coincident hinge is a conversion blocker, not a parser crash')
    report = definition.inspect(hinge(origin, b'x=0.000001,y=0.000002,z=-0.000003'))
    assert not report['diagnostics']
    passed('small nonzero oblique hinge is retained without arbitrary epsilon or cardinal snapping')
    report = definition.inspect(hinge(b'x=1000000000000000000000000000000,y=0,z=0',
                                      b'x=1000000000000000000000000000001,y=0,z=0'))
    assert report['diagnostics'][0]['code'] == 'PIVOT_PRECISION_LOSS'
    passed('distinct exact pivots collapsing in float64 are diagnosed')
    report = definition.inspect(model(b'gear={{root_pivot={x=0,y=0,z=0}}}'))
    assert report['diagnostics'][0]['code'] == 'PIVOT_PAIR_SHAPE'
    passed('missing hinge endpoint is a conversion blocker')
    report = definition.inspect(wheel(b'axis={x=0,y=0,z=-0.0}'))
    assert report['diagnostics'][0]['code'] == 'ZERO_AXIS'
    report = definition.inspect(wheel(b'axis={x=1.000001,y=0,z=-0.0}'))
    assert not report['diagnostics']
    passed('zero vector blocked; approximate unit vector preserved')
    for bad in (b'axis={x=1,y=0}', b'axis={x=1,y="0",z=0}'):
        assert definition.inspect(wheel(bad))['diagnostics'][0]['code'] == 'AXIS_SHAPE'
    passed('axis shape and numeric fields checked')
    assert definition.inspect(model(b'body={geometry={wrong="piece"}}'))['diagnostics'][0]['code'] == 'GEOMETRY_LIST_SHAPE'
    passed('geometry role requires an ordered string list')
    report = definition.inspect(model(b'metadata={axis="label",geometry="map",root_pivot="label"}'))
    assert len(report['diagnostics']) == 3
    assert {item['code'] for item in report['diagnostics']} == {'UNCLASSIFIED_FIELD_CONTEXT'}
    assert not any(item['severity'] == 'conversion_blocker' for item in report['diagnostics'])
    report = definition.inspect(model(b'metadata={Airfoil="notes",blurTexture="editor"}'))
    assert report['selected_reference_and_string_field_counts'] == {'Airfoil_string_field': 1, 'blurTexture_string_field': 1}
    passed('unrecognized structural contexts do not acquire roles from field names alone')
    report = definition.inspect(b'modelTypes.X={\r\nname="\xe9"}')
    span = report['diagnostics'][0]['span']
    assert span == {'start_byte': 21, 'end_byte_exclusive': 24, 'line': 2, 'byte_column': 6}, span
    passed('diagnostic line and byte column match CRLF and raw byte offsets')

    with tempfile.TemporaryDirectory(prefix='openrc-px-mod-check-') as directory:
        path = Path(directory) / 'owned.mod'
        source = model(b'name="original fixture"')
        path.write_bytes(source)
        optimized = subprocess.run([sys.executable, '-O', str(Path(__file__).resolve())],
                                   capture_output=True, text=True, timeout=5)
        assert optimized.returncode == 1 and 'optimized Python' in optimized.stderr
        passed('optimized Python cannot emit passing definition receipts')
        for label, expected_hash, code in [('exact input hash', probe.sha(source), 0),
                                           ('wrong input hash', '0' * 64, 1)]:
            out, err = io.StringIO(), io.StringIO()
            with patch.object(sys, 'argv', ['inspect_definition.py', str(path), '--sha256', expected_hash]):
                with redirect_stdout(out), redirect_stderr(err):
                    actual_code = definition.main()
            assert actual_code == code, (label, err.getvalue())
            if code == 0:
                assert json.loads(out.getvalue())['input_sha256'] == probe.sha(source)
            else:
                assert 'SHA-256 mismatch' in err.getvalue()
            passed('definition CLI ' + label)
    for members in (None, [], [None], [{'sha256': '0' * 64}],
                    [{'sha256': '0' * 64, 'path_components_raw_hex': []}],
                    [{'sha256': '0' * 64, 'path_components_raw_hex': ['not hex']}],
                    [{'sha256': '0' * 64, 'path_components_raw_hex': [123]}]):
        try:
            mod_member_claim({'pkg_probe': {'members': members}}, '0' * 64)
        except ValueError:
            continue
        raise AssertionError('malformed inventory member claim accepted')
    passed('malformed inventory member shapes produce controlled refusals')
    return checks


def mod_member_claim(example, expected_sha):
    members = example['pkg_probe'].get('members')
    if not isinstance(members, list) or not 0 < len(members) <= probe.MAX_MEMBERS:
        raise ValueError('inventory requires a bounded nonempty member list')
    matches = []
    for member in members:
        if not isinstance(member, dict) or not re.fullmatch(r'[0-9a-f]{64}', str(member.get('sha256', ''))):
            raise ValueError('inventory member requires a content hash')
        raw_path = member.get('path_components_raw_hex')
        if not isinstance(raw_path, list) or not 0 < len(raw_path) <= probe.MAX_DEPTH + 1:
            raise ValueError('inventory member requires a bounded raw component list')
        for component in raw_path:
            if (not isinstance(component, str) or len(component) > probe.MAX_TEXT * 2
                    or re.fullmatch(r'(?:[0-9a-f]{2})*', component) is None):
                raise ValueError('inventory raw component is not bounded hex bytes')
        if member['sha256'] == expected_sha and bytes.fromhex(raw_path[-1]).lower().endswith(b'.mod'):
            matches.append(member)
    if len(matches) != 1:
        raise ValueError('pinned MOD is not an unambiguous recorded package member')
    return matches[0]


def run_real(inventory, samples_directory):
    examples = harness.inventory_examples(inventory)
    results = []
    directory_fd = harness.open_samples_directory(samples_directory)
    try:
        for specimen_id, expected_sha in PINNED_MODS.items():
            example = examples.get(specimen_id)
            if example is None:
                raise ValueError('missing pinned inventory specimen: ' + specimen_id)
            member = mod_member_claim(example, expected_sha)
            data = probe.read_regular_file(specimen_id + '.mod', definition.MAX_INPUT,
                                           dir_fd=directory_fd, nofollow=True)
            if probe.sha(data) != expected_sha:
                raise ValueError('local MOD identity mismatch: ' + specimen_id)
            report = definition.inspect(data)
            blockers = [item for item in report['diagnostics'] if item['severity'] == 'conversion_blocker']
            if blockers:
                raise AssertionError('unexpected corpus preflight blocker: ' + specimen_id)
            results.append({'specimen_id': specimen_id,
                            'inventory_reported_package_sha256': example['pkg_probe']['input_sha256'],
                            'inventory_reported_member_path_raw_hex': member['path_components_raw_hex'],
                            'membership_scope': 'Matches a pinned MOD hash and the inventory claim; this command does not recapture or inspect its PKG.',
                            'input_sha256': report['input_sha256'], 'input_bytes': report['input_bytes'],
                            'node_count': report['node_count'], 'token_count': report['token_count'],
                            'counts': report['counts'],
                            'selected_reference_and_string_field_counts': report['selected_reference_and_string_field_counts'],
                            'diagnostic_counts': dict(sorted(Counter(item['code'] for item in report['diagnostics']).items())),
                            'result': 'parsed exact pinned MOD; semantic dependencies unresolved'})
    finally:
        os.close(directory_fd)
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inventory', type=Path)
    parser.add_argument('--samples-dir', type=Path)
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    if not __debug__:
        print('definition checks failed: optimized Python disables required assertions', file=sys.stderr)
        return 1
    if bool(args.inventory) != bool(args.samples_dir):
        parser.error('--inventory and --samples-dir must be provided together')
    try:
        captured, inventory = harness.capture_inventory(args.inventory) if args.inventory else (None, None)
        report = {
            'schema': 'openrc-phoenix-definition-checks-v1',
            'generated_at_utc': datetime.now(timezone.utc).isoformat(),
            'python': platform.python_version(), 'parser_profile': definition.PROFILE,
            'python_optimization': sys.flags.optimize,
            'definition_source_sha256': DEFINITION_SOURCE_SHA256,
            'probe_source_sha256': harness.PROBE_SOURCE_SHA256,
            'checker_on_disk_sha256': probe.sha(probe.read_regular_file(Path(__file__), 512 * 1024)),
            'harness_on_disk_sha256': probe.sha(probe.read_regular_file(Path(harness.__file__), 512 * 1024)),
            'identity_scope': 'In-process parser/probe identities cover captured executed repository source; checker/harness hashes observe on-disk files. Subprocess checks use on-disk tool files. No authentication claim.',
            'scope': 'Observed MOD data grammar and limited preflight only; no dependency resolution, GEO conversion, runtime admission or flight qualification.',
            'synthetic_checks': run_synthetic(),
            'real_samples': run_real(inventory, args.samples_dir) if inventory is not None else [],
        }
        if captured is not None:
            report['inventory_sha256'] = probe.sha(captured)
        output = harness.serialize_check_report(report)
        if args.report:
            harness.write_new_report(args.report, output)
        else:
            print(output, end='')
    except (ValueError, OSError, AssertionError) as exc:
        print(f'definition checks failed: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
