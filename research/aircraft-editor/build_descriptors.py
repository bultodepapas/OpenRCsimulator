#!/usr/bin/env python3
"""Generate Workshop descriptors from catalog entries and exact aircraft bytes."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "research" / "aircraft-standardization"))
from modules import classify as classify_aircraft_modules


CATALOG = ROOT / "app" / "app_state" / "aircraft_catalog.gd"
OUTPUT = ROOT / "app" / "data" / "workshop"
GENERATED_MARKER = "Generated by research/aircraft-editor/build_descriptors.py; do not edit."
ENTRY_RE = re.compile(
    r"\{\s*(?:\#[^\n]*\n\s*)*id\s*=\s*\"(?P<id>[^\"]+)\"(?P<body>.*?)\}",
    re.DOTALL,
)
FAMILY_RE = re.compile(r'\bvisual_family\s*=\s*"(?P<family>[^\"]+)"')
DATA_RE = re.compile(r"\bdata\s*=\s*\"(?P<path>[^\"]*)\"")
ID_RE = re.compile(r"^[a-z0-9][a-z0-9._-]{0,127}$")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def derive_modules(base: dict[str, Any]) -> list[str]:
    result = classify_aircraft_modules(base)
    if not result["ok"]:
        raise ValueError("; ".join(result["errors"]))
    return result["modules"]


def catalog_entries() -> list[tuple[str, str]]:
    source = CATALOG.read_text(encoding="utf-8")
    entries: list[tuple[str, str]] = []
    seen: set[str] = set()
    for match in ENTRY_RE.finditer(source):
        base_id = match.group("id")
        data_match = DATA_RE.search(match.group("body"))
        if data_match is None:
            raise ValueError(f"catalog entry {base_id!r} has no data path")
        data_path = data_match.group("path")
        if not data_path:
            continue
        if not ID_RE.fullmatch(base_id) or base_id in seen:
            raise ValueError(f"invalid or duplicate catalog ID: {base_id!r}")
        if not data_path.startswith("res://data/aircraft/"):
            raise ValueError(f"catalog entry {base_id} uses an unsupported data path: {data_path}")
        seen.add(base_id)
        entries.append((base_id, data_path))
    if not entries:
        raise ValueError("no aircraft catalog data entries were found")
    return entries


def presentation_binding(base_id: str) -> dict[str, str]:
    matches = [match for match in ENTRY_RE.finditer(CATALOG.read_text(encoding="utf-8"))
               if match.group("id") == base_id]
    family_match = FAMILY_RE.search(matches[0].group("body")) if len(matches) == 1 else None
    if family_match is None or not ID_RE.fullmatch(family_match.group("family")):
        raise ValueError(f"{base_id}: missing or invalid catalog visual family")
    family = family_match.group("family")
    manifest_bytes = (ROOT / "app/data/aircraft_models" / f"{family}.json").read_bytes()
    manifest = json.loads(manifest_bytes.decode("utf-8"))
    if manifest.get("schema") != "openrc-aircraft-model" or manifest.get("version") != 1 or manifest.get("family_id") != family:
        raise ValueError(f"{base_id}: invalid model manifest identity")
    return {"visual_family": family, "model_manifest_sha256": sha256(manifest_bytes), "scale_root": "airplane"}


def build_descriptor(base_id: str, resource_path: str) -> dict[str, Any]:
    source_path = ROOT / "app" / resource_path.removeprefix("res://")
    source_bytes = source_path.read_bytes()
    try:
        base = json.loads(source_bytes.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"{resource_path}: invalid UTF-8 JSON: {exc}") from exc
    if not isinstance(base, dict) or base.get("format") != "openrc-aircraft v2":
        raise ValueError(f"{resource_path}: expected an openrc-aircraft v2 object")
    if base.get("id") != base_id:
        raise ValueError(f"{resource_path}: source ID does not match catalog ID {base_id}")
    inventory = base.get("inventory")
    if not isinstance(inventory, list) or not inventory:
        raise ValueError(f"{base_id}: inventory must be a non-empty array")
    bindings: list[dict[str, Any]] = []
    for index, item in enumerate(inventory):
        if not isinstance(item, dict) or not isinstance(item.get("name"), str) or not item["name"]:
            raise ValueError(f"{base_id}: inventory item {index} needs a non-empty name")
        name_hash = sha256(item["name"].encode("utf-8"))
        bindings.append(
            {
                "key": f"inventory-{index:03d}-{name_hash[:12]}",
                "index": index,
                "name_sha256": name_hash,
            }
        )
    return {
        "_generated_do_not_edit": GENERATED_MARKER,
        "format": "openrc-aircraft-workshop v2",
        "base_id": base_id,
        "base_sha256": sha256(source_bytes),
        "inventory_bindings": bindings,
        "modules": derive_modules(base),
        "presentation": presentation_binding(base_id),
    }


def descriptor_bytes(descriptor: dict[str, Any]) -> bytes:
    # Build and write canonical LF bytes so Git checkout settings cannot change the generated file.
    text = json.dumps(descriptor, ensure_ascii=False, indent=2) + "\n"
    return text.replace("\r\n", "\n").replace("\r", "\n").encode("utf-8")


def expected_descriptors() -> dict[Path, bytes]:
    expected: dict[Path, bytes] = {}
    for base_id, resource_path in catalog_entries():
        destination = OUTPUT / f"{base_id}.json"
        expected[destination] = descriptor_bytes(build_descriptor(base_id, resource_path))
    return expected


def check_outputs(expected: dict[Path, bytes]) -> list[str]:
    errors: list[str] = []
    expected_paths = set(expected)
    actual_paths = set(OUTPUT.glob("*.json")) if OUTPUT.exists() else set()
    for path in sorted(expected_paths - actual_paths):
        errors.append(f"missing generated descriptor: {path.relative_to(ROOT)}")
    for path in sorted(actual_paths - expected_paths):
        errors.append(f"unexpected descriptor outside the catalog: {path.relative_to(ROOT)}")
    for path in sorted(expected_paths & actual_paths):
        if path.read_bytes() != expected[path]:
            errors.append(f"stale generated descriptor: {path.relative_to(ROOT)}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated descriptors are stale")
    args = parser.parse_args()
    try:
        expected = expected_descriptors()
        if args.check:
            errors = check_outputs(expected)
            if errors:
                for error in errors:
                    print(error, file=sys.stderr)
                return 1
            print(f"{len(expected)} Workshop descriptors are current.")
            return 0
        OUTPUT.mkdir(parents=True, exist_ok=True)
        for path, content in expected.items():
            path.write_bytes(content)
        for path in set(OUTPUT.glob("*.json")) - set(expected):
            path.unlink()
        print(f"Generated {len(expected)} Workshop descriptors.")
        return 0
    except (OSError, ValueError) as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
