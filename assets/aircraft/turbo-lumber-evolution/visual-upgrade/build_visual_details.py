#!/usr/bin/env python3
"""Build deterministic, render-only Turbo Lumber detail resources from pinned inputs."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
APP = REPO / "app" / "assets" / "aircraft" / "turbo-lumber-evolution" / "visual-upgrade"
SPEC_PATH = HERE / "visual_detail_spec.json"
GEOMETRY_PATH = HERE.parent / "geometry.json"
MEASUREMENTS_PATH = HERE.parent / "mesh-measurements.json"
GLB_PATH = REPO / "app" / "assets" / "aircraft" / "turbo-lumber-evolution" / "timber.glb"
DATA_PATH = APP / "visual_detail_data.gd"
PROVENANCE_PATH = APP / "PROVENANCE.json"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def encoded(value: object) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True)


def generated_files() -> dict[Path, bytes]:
    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    geometry = json.loads(GEOMETRY_PATH.read_text(encoding="utf-8"))
    measurements = json.loads(MEASUREMENTS_PATH.read_text(encoding="utf-8"))
    actual_glb_hash = sha256(GLB_PATH)
    expected_hash = str(spec["source_glb_sha256"])
    if actual_glb_hash != expected_hash or geometry["inputs"]["glb_sha256"] != expected_hash:
        raise ValueError("visual upgrade source GLB hash does not match the pinned r2 geometry")

    meshes = measurements["meshes"]
    for profile in spec["material_profiles"].values():
        for mesh_name in profile.get("meshes", []):
            if mesh_name not in meshes:
                raise ValueError(f"unknown mesh in material profile: {mesh_name}")
    for key in ["fuselage_label", "main_gear_springs"]:
        host = spec["surface_details"][key]["host"]
        if host not in meshes:
            raise ValueError(f"unknown surface detail host: {host}")
    for mesh_name in spec["surface_details"]["main_wheel_hub_fasteners"]["hosts"]:
        if mesh_name not in meshes:
            raise ValueError(f"unknown wheel hub host: {mesh_name}")

    endpoints = geometry["landing_gear"]["suspension"]["cable_endpoints"]
    cable_paths = []
    for side_key in ["der", "izq"]:
        cable = endpoints[side_key]
        cable_paths.append({
            "id": side_key,
            "start": cable["fuselage_eyelet"],
            "end": cable["anchor_rest"],
        })
    runtime_data = {
        "schema": spec["schema"],
        "aircraft_id": spec["aircraft_id"],
        "geometry_revision": geometry["revision"],
        "source_glb_sha256": actual_glb_hash,
        "material_profiles": spec["material_profiles"],
        "surface_details": spec["surface_details"],
        "main_gear_cables": cable_paths,
        "fracture_details": spec["fracture_details"],
        "free_textures": spec["free_textures"],
    }
    data_gd = (
        "# GENERATED by assets/aircraft/turbo-lumber-evolution/visual-upgrade/build_visual_details.py; do not edit.\n"
        "# Render-only detail parameters. This resource never changes model geometry or simulation data.\n"
        "extends RefCounted\n\nconst DATA := " + encoded(runtime_data) + "\n"
    )

    files: dict[Path, bytes] = {DATA_PATH: data_gd.encode("utf-8")}
    provenance = {"assets": []}
    for texture in spec["free_textures"].values():
        record = {
            "asset": texture["id"],
            "source": texture["source_url"],
            "download": texture["download"],
            "license": texture["license"],
            "usage": texture["usage"],
            "source_files": {},
            "runtime_files": {},
        }
        for key, relative_source in texture["maps"].items():
            source_path = HERE / relative_source
            if not source_path.is_file():
                raise FileNotFoundError(source_path)
            runtime_name = texture["runtime_maps"][key]
            runtime_path = APP / "textures" / runtime_name
            payload = source_path.read_bytes()
            files[runtime_path] = payload
            record["source_files"][source_path.name] = sha256(source_path)
            record["runtime_files"][runtime_name] = sha256(source_path)
        provenance["assets"].append(record)
    files[PROVENANCE_PATH] = (encoded(provenance) + "\n").encode("utf-8")
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify outputs without writing")
    args = parser.parse_args()
    try:
        files = generated_files()
    except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError) as error:
        print(f"visual detail generation failed: {error}", file=sys.stderr)
        return 1

    stale = []
    for path, payload in files.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != payload:
                stale.append(str(path.relative_to(REPO)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != payload:
            path.write_bytes(payload)
    if stale:
        print("generated visual detail resources are stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("visual detail resources match their pinned source inputs")
    else:
        print("built deterministic Timber render-only detail resources")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
