def dictionaries():
    data = {code: json.loads((HERE / "locales" / f"{code}.json").read_text(encoding="utf-8")) for code in LOCALES}
    expected = set(data["en"])
    # Do not silently forget a newly supported simulator language.
    registry = (ROOT / "app/i18n/languages.gd").read_text(encoding="utf-8")
    app_locales = set(re.findall(r'^\s*"([\w]+)":', registry, re.M))
    if set(data) != app_locales:
        raise ValueError("Skin-guide locales differ from the simulator language registry")
    for code, strings in data.items():
        if set(strings) != expected:
            raise ValueError(f"{code}: missing/extra translation keys: {set(strings) ^ expected}")
        for key, value in strings.items():
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"{code}.{key}: empty or non-string translation")
        for key, tokens in {
            "prompt_budget": ["2048", "4096", "16 MiB", "32 MiB", "8K"],
            "prompt_paint": ["x8_livery", "x8_abisal_base_color", "sRGB"],
            "prompt_export": ["Export OpenRC Skin.py", ".orskin"],
            "prompt_deliver": ["1920", "1080", ".blend", ".orskin"],
        }.items():
            for token in tokens:
                if token not in strings[key]:
                    raise ValueError(f"{code}.{key}: missing contract token {token}")
        if not re.search(r"16[,. \u00a0\u202f]?777[,. \u00a0\u202f]?216", strings["prompt_budget"]):
            raise ValueError(f"{code}: combined pixel limit differs from the contract")
    return data


def prompt(strings, provider="codex"):
    return "\n\n".join([strings["idea_heading"], strings["idea"], strings["route_heading"],
                         strings["route_" + provider], strings["instructions_heading"],
                         *[strings[key] for key in PROMPT_KEYS]])


def build():
    data = dictionaries()
    esc = html.escape
    parts = ['<!doctype html>\n<!-- Generated by tools/skins/build_guide.py; edit tools/skins/locales/*.json. -->',
             '<html lang="en" data-default-locale="auto"><head><meta charset="utf-8">',
             '<meta name="viewport" content="width=device-width, initial-scale=1"><link rel="icon" href="data:,">',
             '<title>OpenRC · ' + esc(data["en"]["title"]) + '</title><style>' + CSS + '</style></head><body>',
             '<header><div class="wrap"><p class="brand">OpenRC Simulator · X8</p><nav aria-label="Language">']
    for code, name in LOCALES.items():
        parts.append(f'<a href="#{code}" lang="{code.replace("_", "-")}" hreflang="{code.replace("_", "-")}">{esc(name)}</a>')
    parts.append('</nav></div></header><main class="wrap">')
    for code, s in data.items():
        parts.append(f'<section id="{code}" lang="{code.replace("_", "-")}" class="locale"><h1>{esc(s["title"])}</h1><p class="intro">{esc(s["intro"])}</p>')
        def paragraph(key):
            return '<p>' + esc(s[key]) + '</p>'
        def article(title, keys):
            return '<article><h2>' + esc(s[title]) + '</h2>' + ''.join(paragraph(k) for k in keys) + '</article>'
        parts.append(article("get_title", ["get_body", "contents", "blender"]))
        parts.append(article("route_title", ["codex_body", "desktop_body", "cloud_body", "references"]))
        parts.append('<article class="prompt-builder"><h2>' + esc(s["prompt_title"]) + '</h2>' + paragraph("prompt_help"))
        parts.append(f'<label for="idea-{code}">{esc(s["idea_label"])}</label><textarea class="idea" id="idea-{code}" rows="4">{esc(s["idea"])}</textarea>')
        parts.append(f'<label for="provider-{code}">{esc(s["provider_label"])}</label><select class="provider" id="provider-{code}">')
        for provider in ["codex", "desktop", "cloud"]:
            parts.append(f'<option value="{provider}">{esc(s["provider_" + provider])}</option>')
        parts.append(f'</select><label for="prompt-{code}">{esc(s["prompt_label"])}</label><textarea class="prompt" id="prompt-{code}" rows="24" spellcheck="false">{esc(prompt(s))}</textarea>')
        parts.append(f'<button type="button" class="copy">{esc(s["copy"])}</button><p class="status" role="status" aria-live="polite"></p></article>')
        parts.append('<article><h2>' + esc(s["finish_title"]) + '</h2>' + ''.join(paragraph(k) for k in ["save_body", "preview_body", "export_body"]) + '<pre><code>' + esc(COMMAND) + '</code></pre></article>')
        parts.append('<article><h2>' + esc(s["image_title"]) + '</h2>' + paragraph("image_body"))
        parts.append(f'<label for="image-prompt-{code}">{esc(s["image_prompt_label"])}</label><textarea class="image-prompt" id="image-prompt-{code}" rows="16">{esc(s["image_prompt"])}</textarea>')
        parts.append('<button type="button" class="image-copy">' + esc(s["copy"]) + '</button><p class="image-status" role="status" aria-live="polite"></p>')
        parts.append(paragraph("image_steps") + '<pre><code>' + esc(IMAGE_COMMAND) + '</code></pre>' + paragraph("image_limits") + '</article>')
        parts.append('<article><h2>' + esc(s["load_title"]) + '</h2>' + ''.join(paragraph(k) for k in ["load_body", "failure_body", "cleanup_body"]) + '<dl>')
        for system, path in PATHS.items():
            parts.append('<dt>' + system + '</dt><dd><code>' + esc(path) + '</code></dd>')
        parts.append('</dl></article><article><h2>' + esc(s["share_title"]) + '</h2>' + paragraph("share_body") + '<p><a href="mailto:bultodepapas@gmail.com?subject=OpenRC%20X8%20skin">bultodepapas@gmail.com</a></p></article>')
        parts.append('<article><h2>' + esc(s["sources_title"]) + '</h2>' + paragraph("sources_body") + '<ul>')
        for key, url in SOURCES.items():
            parts.append('<li><a href="' + esc(url, quote=True) + '">' + esc(s[key]) + '</a></li>')
        parts.append('</ul></article></section>')
    # JSON cannot close its own script element even when a translated string includes markup.
    payload = json.dumps(data, ensure_ascii=False).replace('<', '\\u003c')
    parts.append('</main><script id="translations" type="application/json">' + payload + '</script><script>' + JS + '</script></body></html>')
    return '\n'.join(parts) + '\n'


