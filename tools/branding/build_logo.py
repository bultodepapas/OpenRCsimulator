"""Pack the official SVG paths, unchanged, into a transparent animation atlas.

Run from any directory with Python's standard library. --check verifies outputs.
"""
import argparse
import copy
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "app/assets/branding"
SVG = "{http://www.w3.org/2000/svg}"


def build():
    source = ET.parse(DEST / "openrc-official.svg").getroot()
    pieces = []
    fragments = []
    x = y = row_height = 0
    for group in source.findall(f"{SVG}g"):
        for path in group.findall(f"{SVG}path"):
            # The supplied vector uses only absolute M/L/Z polygon contours.
            if re.search(r"[A-KN-Y a-kn-y]", path.attrib["d"].replace(" ", "")):
                raise ValueError("Unsupported path command; extend bounds calculation first")
            values = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", path.attrib["d"])]
            left, top = min(values[::2]), min(values[1::2])
            width = max(values[::2]) - left
            height = max(values[1::2]) - top
            w, h = int(width + 24), int(height + 24)
            if x + w > 2048:
                y += row_height
                x = row_height = 0
            item = copy.deepcopy(path)
            item.tag = "path"
            item.set("fill", group.attrib["fill"])
            item.set("fill-rule", "evenodd")
            fragments.append(f'<g transform="translate({x + 12 - left:g} {y + 12 - top:g})">'
                             + ET.tostring(item, encoding="unicode") + '</g>')
            pieces.append({"id": path.attrib["id"], "group": group.attrib["id"],
                           "rect": [left - 12, top - 12, w, h], "atlas": [x, y, w, h]})
            x += w
            row_height = max(row_height, h)
    height = y + row_height
    # 2x rasterization retains clean edges at 4K; the editable master stays SVG.
    atlas = (f'<svg xmlns="http://www.w3.org/2000/svg" width="4096" height="{height * 2}" '
             f'viewBox="0 0 2048 {height}">\n' + "\n".join(fragments) + "\n</svg>\n")
    metadata = ("# Generated by tools/branding/build_logo.py; do not edit.\n"
                "extends RefCounted\n\nconst PIECES := [\n"
                + "\n".join("\t" + json.dumps(piece) + "," for piece in pieces) + "\n]\n")
    return {DEST / "logo-segments.svg": atlas, DEST / "logo_segments.gd": metadata}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for target, content in build().items():
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale generated branding: {target}")
        else:
            target.write_text(content, encoding="utf-8", newline="\n")
    print("Official logo atlas: verified" if args.check else "Official logo atlas: generated")
