#!/usr/bin/env python3
"""Reconstruct this dated audit's minimal project from pinned Git objects.

No production files are changed. The output must not exist. Engine-generated
UID/import/cache metadata is intentionally regenerated by the pinned editor.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[6])
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    root = args.root.resolve()
    evidence = Path(__file__).resolve().parent.parent / "evidence"
    manifest = json.loads((evidence / "fixture-sources.json").read_text())
    target = args.out if args.out.is_absolute() else root / args.out
    target.mkdir(parents=True, exist_ok=False)
    for item in manifest["files"]:
        name = item["path"]
        relative = Path(name)
        if relative.parts[0] != "app" or ".." in relative.parts:
            raise ValueError(f"Invalid recorded source path: {name}")
        data = subprocess.check_output(
            ["git", "show", f"{manifest['base_commit']}:{name}"], cwd=root
        )
        if item["checkout_eol"] == "crlf":
            data = data.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")
        if hashlib.sha256(data).hexdigest() != item["sha256"]:
            raise ValueError(f"Pinned source/checkout byte mismatch: {name}")
        destination = target / relative.relative_to("app")
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
    project = (evidence / "fixture-project.godot").read_bytes()
    if hashlib.sha256(project).hexdigest() != manifest["fixture_project_sha256"]:
        raise ValueError("Recorded fixture project hash mismatch")
    (target / "project.godot").write_bytes(project)
    print(f"Prepared {len(manifest['files'])} hash-verified source files in {target}")
    print("Run the pinned editor import through run_checked.py before tests.")


if __name__ == "__main__":
    main()
